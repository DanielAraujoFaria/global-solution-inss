-- ---------- Catálogo (dados de referência) ----------
CREATE TABLE tipo_exigencia (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo                VARCHAR(40)  NOT NULL UNIQUE,
    titulo                VARCHAR(120) NOT NULL,
    texto_oficial_exemplo VARCHAR(500) NOT NULL,
    explicacao_simples    VARCHAR(600) NOT NULL,
    prazo_padrao_dias     INT          NOT NULL CHECK (prazo_padrao_dias > 0),
    exige_analise_humana  BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE documento_modelo (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_exigencia_id BIGINT       NOT NULL REFERENCES tipo_exigencia (id),
    nome              VARCHAR(160) NOT NULL,
    orientacao        VARCHAR(400) NOT NULL,
    obrigatorio       BOOLEAN      NOT NULL DEFAULT TRUE,
    ordem             INT          NOT NULL
);

-- ---------- Cidadãos e pedidos (fictícios) ----------
CREATE TABLE cidadao (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_ficticio VARCHAR(80) NOT NULL,
    faixa_etaria  VARCHAR(10) NOT NULL CHECK (faixa_etaria IN ('18-39', '40-59', '60+')),
    tipo_acesso   VARCHAR(30) NOT NULL
                  CHECK (tipo_acesso IN ('TITULAR', 'REPRESENTANTE_HABILITADO', 'REPRESENTANTE_NAO_HABILITADO')),
    representa_id BIGINT NULL REFERENCES cidadao (id)
);

CREATE TABLE pedido (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cidadao_id        BIGINT      NOT NULL REFERENCES cidadao (id),
    protocolo         VARCHAR(30) NOT NULL UNIQUE,
    beneficio         VARCHAR(80) NOT NULL,
    status            VARCHAR(20) NOT NULL CHECK (status IN ('EM_ANALISE', 'COM_EXIGENCIA', 'INDEFERIDO')),
    dados_divergentes BOOLEAN     NOT NULL DEFAULT FALSE,
    data_pedido       DATE        NOT NULL
);

CREATE TABLE exigencia (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id           BIGINT       NOT NULL REFERENCES pedido (id),
    tipo_exigencia_id   BIGINT       NOT NULL REFERENCES tipo_exigencia (id),
    texto_oficial       VARCHAR(500) NOT NULL,
    data_emissao        DATE         NOT NULL,
    data_prazo          DATE         NOT NULL,
    status              VARCHAR(15)  NOT NULL DEFAULT 'ABERTA'
                        CHECK (status IN ('ABERTA', 'EM_ANDAMENTO', 'CUMPRIDA', 'ENCAMINHADA')),
    data_cumprimento    DATE NULL,
    lembrete_consentido BOOLEAN      NOT NULL DEFAULT FALSE,
    lembrete_dias_antes INT NULL,
    CHECK (data_prazo >= data_emissao)
);

CREATE TABLE item_checklist (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exigencia_id  BIGINT       NOT NULL REFERENCES exigencia (id),
    nome          VARCHAR(160) NOT NULL,
    orientacao    VARCHAR(400) NOT NULL,
    obrigatorio   BOOLEAN      NOT NULL,
    status        VARCHAR(10)  NOT NULL DEFAULT 'PENDENTE'
                  CHECK (status IN ('PENDENTE', 'PRONTO', 'DUVIDA', 'ILEGIVEL', 'ENVIADO')),
    atualizado_em TIMESTAMP NULL
);

-- ---------- Atendimento (conversa) ----------
CREATE TABLE conversa (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origem                VARCHAR(15) NOT NULL CHECK (origem IN ('DEMONSTRACAO', 'SIMULACAO', 'TESTE_USUARIO')),
    rotulo                VARCHAR(40) NULL,
    cidadao_id            BIGINT NULL REFERENCES cidadao (id),
    motivo_contato        VARCHAR(25) NULL,
    exigencia_id          BIGINT NULL REFERENCES exigencia (id),
    checklist_obrigatorios        INT NULL,
    checklist_obrigatorios_prontos INT NULL,
    autenticada           BOOLEAN     NOT NULL DEFAULT FALSE,
    ref_autenticacao      VARCHAR(64) NULL,
    inicio                TIMESTAMP   NOT NULL,
    fim                   TIMESTAMP NULL,
    desfecho              VARCHAR(25) NOT NULL DEFAULT 'EM_ANDAMENTO'
                          CHECK (desfecho IN ('EM_ANDAMENTO', 'CONCLUIDA_DIGITAL', 'ORIENTADA_MEU_INSS',
                                              'PENDENTE_DOCUMENTOS', 'ENCAMINHADA', 'ABANDONADA')),
    encaminhamento        VARCHAR(15) NULL CHECK (encaminhamento IN ('MEU_INSS', 'CENTRAL_135', 'AGENCIA_APS')),
    motivo_encaminhamento VARCHAR(40) NULL,
    resumo_encaminhamento VARCHAR(1500) NULL
);

CREATE TABLE mensagem (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversa_id BIGINT        NOT NULL REFERENCES conversa (id),
    autor       VARCHAR(10)   NOT NULL CHECK (autor IN ('CIDADAO', 'ASSISTENTE')),
    texto       VARCHAR(2000) NOT NULL,
    mascarada   BOOLEAN       NOT NULL DEFAULT FALSE,
    enviada_em  TIMESTAMP     NOT NULL
);

CREATE TABLE envio_protocolo (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exigencia_id            BIGINT      NOT NULL REFERENCES exigencia (id),
    conversa_id             BIGINT      NOT NULL REFERENCES conversa (id),
    protocolo_simulado      VARCHAR(30) NOT NULL UNIQUE,
    confirmado_pelo_cidadao BOOLEAN     NOT NULL CHECK (confirmado_pelo_cidadao = TRUE),
    enviado_em              TIMESTAMP   NOT NULL
);

CREATE TABLE avaliacao (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversa_id        BIGINT    NOT NULL UNIQUE REFERENCES conversa (id),
    clareza            INT       NOT NULL CHECK (clareza BETWEEN 1 AND 5),
    satisfacao         INT       NOT NULL CHECK (satisfacao BETWEEN 1 AND 5),
    sabe_proximo_passo BOOLEAN   NOT NULL,
    avaliada_em        TIMESTAMP NOT NULL
);

CREATE TABLE auditoria (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversa_id BIGINT       NOT NULL REFERENCES conversa (id),
    evento      VARCHAR(40)  NOT NULL,
    detalhe     VARCHAR(300) NULL,
    ocorrido_em TIMESTAMP    NOT NULL
);

CREATE INDEX idx_pedido_cidadao      ON pedido (cidadao_id);
CREATE INDEX idx_exigencia_pedido    ON exigencia (pedido_id);
CREATE INDEX idx_item_exigencia      ON item_checklist (exigencia_id);
CREATE INDEX idx_mensagem_conversa   ON mensagem (conversa_id);
CREATE INDEX idx_conversa_desfecho   ON conversa (desfecho);
CREATE INDEX idx_auditoria_conversa  ON auditoria (conversa_id);
